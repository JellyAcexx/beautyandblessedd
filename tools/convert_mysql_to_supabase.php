function q($name) {
    return '"' . str_replace('"', '""', $name) . '"';
}

function convertColumn($table, $column, $definition, $identityCols) {
    $definition = trim(rtrim($definition, ','));
    $definition = preg_replace('/\bUNSIGNED\b/i', '', $definition);
    $definition = preg_replace('/\s+/', ' ', $definition);

    $notNull = preg_match('/\bNOT NULL\b/i', $definition) === 1;
    $default = null;
    if (preg_match('/\bDEFAULT\s+([^ ]+(?:\s*\([^)]*\))?)/i', $definition, $match)) {
        $default = rtrim($match[1], ',');
        if (strtolower($default) === 'current_timestamp()') {
            $default = 'CURRENT_TIMESTAMP';
        } elseif (strtolower($default) === 'null') {
            $default = null;
        }
    }

    if (($identityCols[$table] ?? null) === $column) {
        $type = 'integer GENERATED BY DEFAULT AS IDENTITY';
    } elseif (preg_match('/^int\(\d+\)/i', $definition)) {
        $type = 'integer';
    } elseif (preg_match('/^tinyint\(1\)/i', $definition)) {
        $type = 'smallint';
    } elseif (preg_match('/^decimal\((\d+),(\d+)\)/i', $definition, $match)) {
        $type = 'numeric(' . $match[1] . ',' . $match[2] . ')';
    } elseif (preg_match('/^varchar\((\d+)\)/i', $definition, $match)) {
        $type = 'varchar(' . $match[1] . ')';
    } elseif (preg_match('/^text\b/i', $definition)) {
        $type = 'text';
    } elseif (preg_match('/^timestamp\b/i', $definition)) {
        $type = 'timestamp without time zone';
    } elseif (preg_match('/^datetime\b/i', $definition)) {
        $type = 'timestamp without time zone';
    } elseif (preg_match('/^date\b/i', $definition)) {
        $type = 'date';
    } elseif (preg_match("/^enum\('unread','read'\)/i", $definition)) {
        $type = 'varchar(20) CHECK (' . q($column) . " IN ('unread', 'read'))";
    } elseif (preg_match("/^enum\('Login','Logout'\)/i", $definition)) {
        $type = 'varchar(20) CHECK (' . q($column) . " IN ('Login', 'Logout'))";
    } else {
        throw new RuntimeException("Unhandled type for {$table}.{$column}: {$definition}");
    }

    $parts = [q($column), $type];
    if ($table === 'purchase' && $column === 'reservation_id') {
        $notNull = false;
    }

    if ($notNull) {
        $parts[] = 'NOT NULL';
    }
    if ($default !== null && (($identityCols[$table] ?? null) !== $column)) {
        $parts[] = 'DEFAULT ' . $default;
    }

    return '    ' . implode(' ', $parts);
}

$output = [
    '-- PostgreSQL/Supabase conversion of database/blessed.sql',
