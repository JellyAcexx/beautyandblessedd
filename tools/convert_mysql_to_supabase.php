preg_match_all('/CREATE TABLE `([^`]+)` \(/', $text, $tableMatches);
$tables = $tableMatches[1];
foreach (array_reverse($tables) as $table) {
    $output[] = 'DROP TABLE IF EXISTS ' . q($table) . ' CASCADE;';
}
$output[] = '';

preg_match_all('/CREATE TABLE `([^`]+)` \((.*?)\) ENGINE=/s', $text, $createMatches, PREG_SET_ORDER);
foreach ($createMatches as $createMatch) {
    $table = $createMatch[1];
    $body = $createMatch[2];
    $columns = [];
    foreach (preg_split('/\R/', $body) as $line) {
        $line = trim($line);
        if ($line === '' || $line[0] !== '`') {
            continue;
        }
        if (!preg_match('/`([^`]+)`\s+(.+)/', $line, $columnMatch)) {
            continue;
        }
        $columns[] = convertColumn($table, $columnMatch[1], $columnMatch[2], $identityCols);
    }

    if (isset($primaryKeys[$table])) {
        $pkCols = array_map('q', $primaryKeys[$table]);
        $columns[] = '    CONSTRAINT ' . q($table . '_pkey') . ' PRIMARY KEY (' . implode(', ', $pkCols) . ')';
    }

    $output[] = 'CREATE TABLE ' . q($table) . ' (';
    $output[] = implode(",\n", $columns);
    $output[] = ');';
    $output[] = '';
}

preg_match_all('/INSERT INTO `([^`]+)` \((.*?)\) VALUES\n(.*?);/s', $text, $insertMatches, PREG_SET_ORDER);
foreach ($insertMatches as $insertMatch) {
    $table = $insertMatch[1];
    preg_match_all('/`([^`]+)`/', $insertMatch[2], $columnMatches);
    $columns = $columnMatches[1];
    $values = str_replace("\\'", "''", $insertMatch[3]);

    $output[] = 'INSERT INTO ' . q($table) . ' (' . implode(', ', array_map('q', $columns)) . ') VALUES';
    $output[] = $values;
    $output[] = ';';
    $output[] = '';
}

foreach ($indexes as [$table, $name, $columns]) {
    $output[] = 'CREATE INDEX ' . q('idx_' . $table . '_' . $name) . ' ON ' . q($table) . ' (' . implode(', ', array_map('q', $columns)) . ');';
}
$output[] = '';

$output[] = 'ALTER TABLE "products" ADD CONSTRAINT "products_category_id_fkey" FOREIGN KEY ("category_id") REFERENCES "category" ("category_id") ON DELETE CASCADE ON UPDATE CASCADE;';
$output[] = '';

foreach ($identityCols as $table => $column) {
    $safeTable = str_replace("'", "''", $table);
    $safeColumn = str_replace("'", "''", $column);
    $output[] = "SELECT setval(pg_get_serial_sequence('{$safeTable}', '{$safeColumn}'), COALESCE((SELECT MAX(" . q($column) . ') FROM ' . q($table) . "), 1), (SELECT MAX(" . q($column) . ') IS NOT NULL FROM ' . q($table) . '));';
}

$output[] = '';
$output[] = 'COMMIT;';
$output[] = '';

file_put_contents($target, implode("\n", $output));
